function stripPartials(html) {
  let prev, out = String(html).replace(/\r\n/g, '\n');
  do { prev = out; out = out.replace(/<!--\s*@([A-Za-z0-9][A-Za-z0-9_-]*)\s*-->[\s\S]*?<!--\s*\/@\1\s*-->/g, '<!-- @$1 --><!-- /@$1 -->'); } while (out !== prev);
  return out;
}

function run(opts) {
  const root = opts.root;
  const D = load(root);
  const items = (D.E.items || []).slice().sort((a, b) => Date.parse(a.start) - Date.parse(b.start));
  const report = { written: [], same: [], removed: [], problems: [] };
  const want = new Set();
  for (const e of items) {
    for (const L of ['en', 'es']) {
      const rel = (L === 'es' ? 'es/' : '') + 'events/' + e.id + '.html';
      want.add(rel);
      const file = path.join(root, rel);
      const html = page(e, D, L, items);
      const disk = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
      if (disk != null && stripPartials(disk) === stripPartials(html)) { report.same.push(rel); continue; }
      if (opts.check) { report.problems.push(rel + (disk == null ? ' is missing' : ' is out of date')); continue; }
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, html);
      report.written.push(rel);
    }
  }
  for (const dir of ['events', 'es/events']) {
    const abs = path.join(root, dir);
    if (!fs.existsSync(abs)) continue;
    for (const f of fs.readdirSync(abs)) {
      const rel = dir + '/' + f;
      if (!/\.html$/.test(f) || want.has(rel)) continue;
      const txt = fs.readFileSync(path.join(abs, f), 'utf8');
      if (txt.indexOf(MARK) < 0) continue;
      if (opts.check) report.problems.push(rel + ' is left over from an event that is gone');
      else { fs.unlinkSync(path.join(abs, f)); report.removed.push(rel); }
    }
  }
  if (!opts.check && opts.sync && report.written.length) {
    const r = spawnSync('python3', [path.join(__dirname, 'sync_partials.py'), '--root', root, '--quiet'].concat(report.written.map((p) => path.join(root, p))), { encoding: 'utf8' });
    if (r.status !== 0) report.problems.push('sync_partials.py exited ' + r.status + ': ' + ((r.stdout || '') + (r.stderr || '')).trim().split('\n').slice(-3).join(' | '));
  }
  report.pages = want.size;
  return report;
}

if (require.main === module) {
  let opts;
  try { opts = parseArgs(process.argv.slice(2)); } catch (e) { console.error('make_event_pages: ' + e.message); process.exit(2); }
  try {
    const r = run(opts);
    if (!opts.quiet) {
      if (r.written.length) console.log('wrote ' + r.written.join(', '));
      if (r.removed.length) console.log('removed ' + r.removed.join(', '));
      for (const p of r.problems) console.log('problem: ' + p);
    }
    const en = Array.from({ length: r.pages }).length / 2;
    console.log('make_event_pages: ' + en + ' EN + ' + en + ' ES pages, ' + r.written.length + ' written, ' + r.same.length + ' unchanged, ' + r.removed.length + ' removed, ' + r.problems.length + ' problems' + (opts.check ? ' (check)' : ''));
    process.exit(r.problems.length ? 1 : 0);
  } catch (e) { console.error('make_event_pages crashed: ' + (e && e.stack || e)); process.exit(2); }
}

module.exports = { run, page, load, parseArgs };
