#!/usr/bin/env node
/**
 * tools/make_event_pages.js (W2): writes one static event / invite page per event in data/events.js, in
 * English (events/<id>.html) and Spanish (es/events/<id>.html), so link previews carry the event without
 * JavaScript and every detail shows with JavaScript off (BRIEF 4.3, 7.5, 7.11).
 *
 *   node tools/make_event_pages.js            # write the pages (then fills partials with sync_partials.py)
 *   node tools/make_event_pages.js --check    # write nothing; exit 1 if any page is missing or stale
 *   options: --root DIR  --no-sync  --quiet
 *
 * Idempotent: a page is rewritten only when its content (partials aside) changed, so a second run writes
 * nothing. Pages for events that left the data file are removed, but only files carrying this tool's
 * GENERATED marker. Each page gets static OG tags, a ysd:og meta (template og-event) for tools/make_og.js
 * (assets/img/og/events/<id>.png and og/es/events/<id>.png), hreflang pairs, a calendar file link
 * (data: URL) plus Google and Outlook links, and I'm in as a plain link to join.html?e=<id> that
 * assets/js/rsvp.js upgrades to the RSVP sheet. Copy comes from data/events.js, data/pages/events.js and
 * data/strings.js; nothing is invented here. Times are New York time, written "7 pm" / "7 p. m.".
 * Exit codes: 0 ok, 1 --check found problems, 2 crash.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { spawnSync } = require('child_process');

const MARK = 'GENERATED by tools/make_event_pages.js';
const TZ = 'America/New_York';

function parseArgs(argv) {
  const o = { root: path.resolve(__dirname, '..'), check: false, sync: true, quiet: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--check') o.check = true;
    else if (a === '--no-sync') o.sync = false;
    else if (a === '--quiet') o.quiet = true;
    else if (a === '--root') o.root = path.resolve(argv[++i]);
    else throw new Error('unknown option ' + a);
  }
  return o;
}

/* ------------------------------------------------------------------ data */
function load(root) {
  const sb = { console: { log() {}, warn() {}, error() {} } };
  sb.window = sb; sb.self = sb; sb.YSD_DATA = {};
  vm.createContext(sb);
  for (const f of ['data/strings.js', 'data/events.js', 'data/pages/events.js']) {
    vm.runInContext(fs.readFileSync(path.join(root, f), 'utf8'), sb, { filename: f });
  }
  // config + cal.js, so static calendar links match what the page builds at runtime
  const cs = { console: sb.console, location: { href: 'https://example.invalid/', search: '' } };
  cs.window = cs; cs.self = cs;
  vm.createContext(cs);
  vm.runInContext(fs.readFileSync(path.join(root, 'assets/js/config.js'), 'utf8'), cs, { filename: 'config.js' });
  vm.runInContext(fs.readFileSync(path.join(root, 'assets/js/cal.js'), 'utf8'), cs, { filename: 'cal.js' });
  return { S: sb.YSD_DATA.strings.entries, E: sb.YSD_DATA.events, P: sb.YSD_DATA.pages.events, YSD: cs.YSD, conf: cs.YSD_CONFIG || (cs.YSD && cs.YSD.config) || {} };
}

function makeText(D, L) {
  const tx = (o) => (o == null ? '' : typeof o === 'string' ? o : (o[L] != null ? o[L] : o.en || ''));
  const fill = (s, v) => String(s == null ? '' : s).replace(/\{(\w+)\}/g, (m, k) => (v && v[k] != null ? String(v[k]) : m));
  const s = (k, v) => fill(tx(D.S[k]), v);
  const p = (k, v) => fill(tx(D.P[k]), v);
  const l = (k, v) => fill(tx((D.E.labels || {})[k]), v);
  return { tx, fill, s, p, l };
}

/* ------------------------------------------------------------------ dates (same rules as assets/js/ui.js) */
function parts(iso, L) {
  const f = new Intl.DateTimeFormat(L === 'es' ? 'es-US' : 'en-US', { timeZone: TZ, weekday: 'short', month: 'short', day: 'numeric', year: 'numeric', hour: 'numeric', minute: '2-digit', hour12: true });
  const o = {};
  f.formatToParts(new Date(iso)).forEach((x) => { o[x.type] = x.value; });
  o.weekday = String(o.weekday || '').replace(/\.$/, '');
  o.month = String(o.month || '').replace(/\.$/, '');
  o.ampm = /p/i.test(o.dayPeriod || '') ? 'pm' : 'am';
  return o;
}
function dateFns(T, L) {
  const time = (iso, bare) => {
    const q = parts(iso, L);
    const hm = q.hour + (q.minute && q.minute !== '00' ? ':' + q.minute : '');
    return bare ? hm : hm + ' ' + (T.s('format.ampm.' + q.ampm) || q.ampm);
  };
  const date = (iso, year) => {
    const q = parts(iso, L);
    const pat = T.s(year ? 'format.dateYear' : 'format.date');
    return pat.replace('{weekday}', q.weekday).replace('{month}', q.month).replace('{day}', q.day).replace('{year}', q.year);
  };
  const when = (a, b) => {
    const x = parts(a, L), y = parts(b, L);
    const range = T.s('format.timeRange');
    const st = x.ampm === y.ampm ? time(a, true) : time(a);
    return date(a) + ' · ' + range.replace('{start}', st).replace('{end}', time(b));
  };
  return { time, date, when, parts: (iso) => parts(iso, L) };
}

/* ------------------------------------------------------------------ html helpers */
const esc = (s) => String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const attr = (s) => esc(s).replace(/"/g, '&quot;');
function hash(s) { let h = 0; for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) | 0; return Math.abs(h); }
const AVATAR_COLORS = ['var(--bubblegum)', 'var(--sky)', 'var(--tangerine)', 'var(--celery)', 'var(--mint)', 'var(--sun)'];
const INITIALS = 'ADJKLMNRSTVYBCEGP';
const photoUrl = (id, w) => 'https://images.unsplash.com/photo-' + id + '?w=' + w + '&q=60&auto=format&fit=crop';

function cfgGet(conf, p, fb) {
  let o = conf;
  for (const k of String(p).split('.')) { if (o == null || typeof o !== 'object') return fb; o = o[k]; }
  return o === undefined || o === '' ? fb : o;
}

function ticket(e, F) {
  const q = F.parts(e.start);
  return '<span class="ticket" aria-hidden="true"><span class="ticket__month">' + esc(q.month) + '</span><span class="ticket__day">' + esc(q.day) + '</span><span class="ticket__time">' + esc(F.time(e.start)) + '</span></span>';
}
function facepile(e, size) {
  const h = hash(e.id), n = +e.going || 0;
  let out = '<span class="facepile" aria-hidden="true">', shown = 0;
  for (let i = 0; i < 3 && i < n; i++, shown++) {
    out += '<span class="avatar' + (size === 'sm' ? ' avatar--sm' : '') + '" style="--avatar: ' + AVATAR_COLORS[(h + i) % AVATAR_COLORS.length] + '">' + INITIALS.charAt((h >> (i * 4)) % INITIALS.length) + '</span>';
  }
  if (n > shown) out += '<span class="facepile__more">+' + (n - shown) + '</span>';
  return out + '</span>';
}
function srcLink(u, T) {
  let host = u;
  try { host = new URL(u).hostname.replace(/^www\./, ''); } catch (e) { /* keep */ }
  return '<a class="link link--out" href="' + attr(u) + '" rel="noopener" target="_blank">' + esc(T.p('ev.source')) + ': <span translate="no">' + esc(host) + '</span></a>';
}
function isFull(e) { return e.status === 'full' || (+e.capacity > 0 && +e.going >= +e.capacity); }
function goingRow(e, T, size) {
  const n = +e.going || 0, left = (+e.capacity || 0) - n;
  let extra = '';
  if (isFull(e)) extra = '<span class="tag tag--outline">' + esc(T.l('fullDemo')) + '</span>';
  else if (+e.capacity && left <= 6) extra = '<span class="invite__left">' + esc(T.l('spotsLeftDemo', { n: left })) + '</span>';
  return '<div class="invite__going" data-rsvp-going="' + attr(e.id) + '"' + (size ? ' data-size="' + size + '"' : '') + '>' + facepile(e, size || 'sm') +
    '<span class="invite__count" data-rsvp-count="' + attr(e.id) + '">' + esc(T.l('going', { n })) + '</span>' + extra + '</div>';
}

